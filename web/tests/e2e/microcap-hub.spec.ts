import { expect, test } from '@playwright/test';

test('hub connects questions, source-backed charts and revised evidence in both languages', async ({ page }) => {
  await page.goto('research/microcap/?lang=en-US');
  await expect(page.locator('#microcap-map').getByRole('link')).toHaveCount(6);
  await page.locator('.topic-nav').getByRole('link', { name: 'Research map', exact: true }).click();
  const mapHeading = await page.locator('#microcap-map h2').boundingBox();
  const masthead = await page.locator('.site-header').boundingBox();
  expect(mapHeading!.y).toBeGreaterThanOrEqual(masthead!.y + masthead!.height);
  const links = await page.locator('#microcap-map a').evaluateAll(nodes => nodes.map(node => (node as HTMLAnchorElement).href));
  for (const href of links) expect((await page.request.get(href)).status()).toBe(200);
  const windows = page.locator('#microcap-window-evidence');
  await expect(windows).toContainText('2015–2026');
  await expect(windows.locator('[data-metric-panel="return"]')).toContainText('7.60%');
  await windows.getByRole('button', { name: 'Maximum drawdown', exact: true }).click();
  await expect(windows.locator('[data-metric-panel="drawdown"]')).toBeVisible();
  await expect(windows.locator('[data-metric-panel="return"]')).toBeHidden();
  await expect(windows.locator('[data-metric-panel="drawdown"]')).toContainText('-65.01%');
  const matrix = page.locator('#microcap-rule-matrix');
  await expect(matrix.locator('tbody td')).toHaveCount(16);
  await expect(matrix).toContainText('weight-level screening engine');
  await expect(page.locator('#microcap-revisions')).toContainText('Next-session execution');
  await expect(page.locator('#microcap-open-questions')).toContainText('Partial evidence; verification remains open');
  await expect(page.locator('#microcap-window-recheck')).toContainText('4.22%');
  await expect(page.locator('#microcap-window-recheck')).toContainText('6.26%');
  await expect(page.locator('#microcap-window-recheck')).toContainText('does not establish which run matches the historical method');
  await page.getByRole('button', { name: 'Switch to Chinese' }).click();
  await expect(page.locator('#microcap-map')).toContainText('研究地图');
  await expect(page.locator('#microcap-window-recheck')).toContainText('还不能确认哪种口径符合当年的原始方法');
  await expect(page.locator('#microcap-window-evidence')).toContainText('最大回撤');
  await expect(page.locator('#microcap-revisions')).toContainText('下一交易日执行');
});

test('hub and numerical evidence remain readable without JavaScript on mobile', async ({ browser }) => {
  const context = await browser.newContext({ javaScriptEnabled: false, viewport: { width: 390, height: 844 } });
  const page = await context.newPage();
  await page.goto('research/microcap/');
  await expect(page.locator('#microcap-map')).toContainText('Research map');
  await expect(page.locator('#microcap-window-evidence')).toContainText('7.60%');
  const sourceLink = page.locator('#microcap-window-evidence a[href$="low_turnover_exploration.json"]');
  expect((await page.request.get((await sourceLink.getAttribute('href'))!)).status()).toBe(200);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await context.close();
});

test('history register, report and download retain the same reviewed families in Chinese dark mode', async ({ page }) => {
  await page.goto('research/microcap/?lang=zh-CN');
  const register=page.locator('#microcap-coverage');
  await expect(register.locator('details')).toHaveCount(35);
  await register.locator('#history-H19 summary').click();
  await expect(register.locator('#history-H19')).toContainText('结构检查通过');
  const recovery=page.locator('#microcap-evidence-recovery');
  await expect(recovery.locator('details')).toHaveCount(7);
  await recovery.locator('#recovery-R04 summary').click();
  await expect(recovery.locator('#recovery-R04')).toContainText('来源链不完整');
  await register.getByRole('link').click();
  await expect(page.locator('.article-content')).toContainText('研究历史与覆盖清单');
  await expect(page.locator('.article-content')).toContainText('H32 · 港股');
  await expect(page.locator('.article-content')).toContainText('七档资金情景');
  const markdown=await (await page.request.get('downloads/microcap-research.zh-CN.md')).text();
  expect(markdown).toContain('### H32 · 港股');
  expect(markdown).toContain('56 条来源记录');
  expect(markdown).toContain('### H35');
  expect(markdown).toContain('### R04');
  await expect(page.locator('.article-content')).toContainText('精确结果包仍缺失');
  await page.evaluate(()=>{localStorage.setItem('market-research-theme','dark');document.documentElement.dataset.theme='dark';});
  const chart=page.locator('.article-content svg').filter({has:page.locator('title#candidate-title')});
  await expect(chart).toBeVisible();
  expect(await chart.locator('rect').first().evaluate(el=>getComputedStyle(el).fill)).not.toBe('rgb(255, 255, 255)');
  await page.getByRole('button',{name:'切换到英文'}).click();
  await expect(page.locator('.article-content')).toContainText('H32 · Hong Kong');
  await expect(page.locator('.article-content')).not.toContainText('七档资金情景');
});
